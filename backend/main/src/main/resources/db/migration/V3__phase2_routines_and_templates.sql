CREATE TABLE IF NOT EXISTS routine_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    descripcion VARCHAR(500),
    profesor_id BIGINT NOT NULL REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS routine_template_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id BIGINT NOT NULL REFERENCES routine_templates(id) ON DELETE CASCADE,
    exercise_id BIGINT NOT NULL REFERENCES exercises(id) ON DELETE CASCADE,
    dia VARCHAR(64) DEFAULT 'Día 1',
    sets INTEGER,
    reps INTEGER,
    peso_sugerido DOUBLE PRECISION,
    descanso_segundos INTEGER DEFAULT 90,
    notas_extras VARCHAR(255)
);

CREATE INDEX IF NOT EXISTS idx_routine_templates_profesor_id ON routine_templates(profesor_id);
CREATE INDEX IF NOT EXISTS idx_routine_template_items_template_id ON routine_template_items(template_id);
